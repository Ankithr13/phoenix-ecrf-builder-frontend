"""Write docs/db-schema.md from the models, so its columns cannot drift.

    python scripts/db_schema.py

The columns come from the SQLAlchemy metadata. Only the sentence on why each
table exists is written by hand, here. tests/test_docs.py fails if the file is
out of date or a table has no sentence.
"""

import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))

from ecrf.storage.models import Base  # noqa: E402

OUTPUT = BACKEND.parent.parent / "docs" / "db-schema.md"

WHY = {
    "organisation": "The sponsor and the sites. A person belongs to one, and what they can reach starts from it.",
    "user": "The people who can sign in, each with one role.",
    "monitor_site": "Which sites each monitor is assigned to, because a monitor sees those sites and no others.",
    "user_access_event": "The append-only record of who was granted what, plus data exports, which the client's roles document asks for.",
    "session": "Who is signed in. Holds a hash of the login token, never the token.",
    "protocol": "One uploaded protocol, with its normalised text and the two approval chain switches and the study lock.",
    "llm_call": "One row per model call, so cost is measured and an identical request can be answered from the cache.",
    "ecrf_version": "Whole snapshots of the form. A new row for every change and never an update, which makes this the form's audit trail.",
    "field_comment": "Reviewers' notes on a field. Attached by field_id, so they survive a rename.",
    "form_field_history": "What changed between versions, one attribute at a time: old value, new value, who, when and why. Also records the form lock, the study lock, and changes to edit checks and the analysis plan.",
    "edit_check": "The checks on a form, as data rows rather than code, so a person can read, switch off or add one.",
    "protocol_site": "Which sites are assigned to which protocol. A site sees only studies listed here whose form is locked.",
    "subject": "A patient at one site on one protocol, known by a server-generated code. Never a name or initials.",
    "observation": "One entered value, or an answer such as Not done, with how far it has got through the approval chain.",
    "observation_history": "Every change to an entered value: old, new, who, when and why. Nothing is overwritten without a row here.",
    "query": "A question about a value, a visit, a patient or the study, raised by a person or an edit check.",
    "signoff": "An investigator's recorded confirmation of a visit, kept even after a later change undoes it.",
    "notification": "Messages in the app for one person about one event. Nothing is emailed.",
    "sap_item": "One row of the statistical analysis plan: which field and visits the fixed calculations work on.",
}


def render() -> str:
    tables = Base.metadata.sorted_tables
    missing = [t.name for t in tables if t.name not in WHY]
    if missing:
        raise SystemExit(f"Write a sentence in WHY for: {', '.join(missing)}")
    out = ["# Database schema", "",
           "Generated by `backend/scripts/db_schema.py` from the models. Do not edit by hand:",
           "change the models or the sentences in that script, then run it. `tests/test_docs.py`",
           "fails if this file is out of date.", "",
           "Alembic's own `alembic_version` table is left out.", ""]
    for t in sorted(tables, key=lambda x: x.name):
        out += [f"## `{t.name}`", "", WHY[t.name], "",
                "| Column | Type | Null | Key |", "|---|---|---|---|"]
        for c in t.columns:
            keys = ["primary key"] if c.primary_key else []
            keys += [f"→ `{fk.target_fullname}`" for fk in c.foreign_keys]
            kind = str(c.type).replace("VARCHAR", "String").replace("DATETIME", "DateTime")
            out.append(f"| `{c.name}` | {kind} | {'yes' if c.nullable else 'no'} | {', '.join(keys)} |")
        uniques = [con for con in t.constraints if con.__class__.__name__ == "UniqueConstraint"]
        for con in uniques:
            out += ["", "Unique together: " + ", ".join(f"`{c.name}`" for c in con.columns)]
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    OUTPUT.write_text(render())
    print(f"wrote {OUTPUT}")
